import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";
import { MemoryRouter } from "react-router-dom";
import type { ReactNode } from "react";
import type { BuilderConversation, BuilderSummary } from "../core/api";
import { BuildList, ChatColumn, IDLE_POLL_MS, arrivalLabel, dropSent, isNearBottom, liveLinkLabel, mergeConversation, pillOf, pollDelay, pollEvery, preferLive, sameThread, startFailureNote, workLine } from "./BuilderApp";
import { elapsedLabel, openQuestion, questionViews, workingStep } from "../../functions/builderHelp.js";

const html = (node: ReactNode) => renderToStaticMarkup(<MemoryRouter>{node}</MemoryRouter>);
const summary = (over: Partial<BuilderSummary> = {}): BuilderSummary => ({ id: "abc", title: "Notes mini app", status: "running", prUrl: null, branch: null, error: null, askedBy: "Rambod", updatedAt: "2026-11-22T18:00:00.000Z", ship: null, adminNotice: null, ...over });
const conversation = (over: Partial<BuilderConversation> = {}): BuilderConversation => ({ ...summary(), agentUrl: "https://cursor.com/agents/bc-1", messages: [{ id: "m1", kind: "user", text: "Add a notes mini app.", at: "2026-11-22T18:00:00.000Z" }, { id: "m2", kind: "assistant", text: "Opened the pull request.\nLive route: /notes", at: "2026-11-22T18:04:00.000Z" }], ...over });

describe("Builder chat", () => {
  it("lists past builds by their short title", () => {
    const out = html(<BuildList items={[summary(), summary({ id: "done", title: "Fix the form", status: "finished", ship: { phase: "live", detail: null } })]} current="abc" />);
    expect(out).toContain("Notes mini app");
    expect(out).toContain("Running");
    expect(out).toContain("Live");
    expect(out).toContain('href="/builder/abc"');
    expect(out).toContain('aria-current="page"');
  });
  it("shows streamed replies, a working row, and the live or failed result", () => {
    const early = html(<ChatColumn now={Date.parse("2026-11-22T18:00:02.000Z")} conversation={conversation({ messages: [{ id: "m1", kind: "user", text: "Add a questionnaire.", at: "2026-11-22T18:00:00.000Z" }] })} />);
    expect(early).toContain("0:02");
    expect(early).toContain("Starting");
    expect(early).not.toContain("Still working");
    expect(early).not.toContain("bd-dots");
    const five = html(<ChatColumn now={Date.parse("2026-11-22T18:00:06.000Z")} conversation={conversation({ messages: [{ id: "m1", kind: "user", text: "Add a questionnaire.", at: "2026-11-22T18:00:00.000Z" }] })} />);
    expect(five).toContain("0:06");
    expect(five).toContain("Starting");
    const running = html(<ChatColumn now={Date.parse("2026-11-22T18:00:42.000Z")} conversation={conversation({ messages: [{ id: "m1", kind: "user", text: "Add a questionnaire.", at: "2026-11-22T18:00:00.000Z" }], live: { step: "Running Install deps and run tests", text: "I'll update the Wells page so the spud date shows on the card.", updatedAt: "2026-11-22T18:00:40.000Z" } })} />);
    expect(running).toContain("0:42");
    expect(running).toContain("update the Wells page so the spud date shows on the card.");
    expect(running).toContain("Running Install deps and run tests");
    expect(running).toContain("bd-work-step");
    expect(running).not.toContain("Still working");
    const live = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} conversation={conversation({ status: "finished", prUrl: "https://github.com/rambodc/uniq/pull/12", ship: { phase: "live", detail: null } })} />);
    expect(live).toContain("Opened the pull request.");
    expect(live).toContain("Live route: /notes");
    expect(live).not.toContain("Open the change");
    expect(live).not.toContain("Hard refresh");
    const failed = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} onFix={() => {}} conversation={conversation({ ship: { phase: "failed", detail: "frontend failed." } })} />);
    expect(failed).toContain("Failed");
    expect(failed).toContain("frontend failed.");
    expect(failed).toContain("Ask Builder to fix");
    expect(pillOf("running", null).label).toBe("Running");
    expect(pillOf("finished", { phase: "merged", detail: "No changes." }).label).toBe("No changes");
    const empty = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} conversation={conversation({ status: "finished", ship: { phase: "merged", detail: "No changes." } })} />);
    expect(empty).toContain("No changes");
    expect(empty).toContain("The merge did not change production.");
    expect(empty).not.toContain("bd-done");
    expect(empty).not.toContain("your change is ready");
    const waitingDeploy = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} conversation={conversation({ status: "finished", prUrl: "https://github.com/rambodc/uniq/pull/12", ship: { phase: "merged", detail: "Merged. Waiting for the production deploy." } })} />);
    expect(waitingDeploy).toContain("Waiting for the production deploy.");
    expect(waitingDeploy).not.toContain("bd-done");
    const deploying = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} conversation={conversation({ status: "finished", prUrl: "https://github.com/rambodc/uniq/pull/12", ship: { phase: "deploying", detail: "Deploying to production." } })} />);
    expect(deploying).toContain("Deploying to production.");
    expect(deploying).not.toContain("your change is ready");
    const ready = "It's live on uniqenergy.com — your change is ready.";
    const celebrated = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} conversation={conversation({ status: "finished", prUrl: "https://github.com/rambodc/uniq/pull/12", ship: { phase: "live", detail: "Live on uniqenergy.com." }, messages: [{ id: "m1", kind: "user", text: "Add a notes mini app.", at: "2026-11-22T18:00:00.000Z" }, { id: "m2", kind: "assistant", text: "Opened the pull request.\nLive route: /notes", at: "2026-11-22T18:04:00.000Z" }, { id: "live-12", kind: "notice", tone: "live", text: ready, href: "https://uniqenergy.com/notes", prUrl: "https://github.com/rambodc/uniq/pull/12", at: "2026-11-22T18:06:00.000Z" }] })} />);
    expect(celebrated.match(/your change is ready/g)?.length).toBe(1);
    expect(celebrated).toContain("bd-done");
    expect(celebrated).toContain('href="https://uniqenergy.com/notes"');
    expect(celebrated).toContain("uniqenergy.com/notes");
    const pendingCard = html(<ChatColumn now={Date.parse("2026-11-22T18:04:00.000Z")} conversation={conversation({ status: "finished", prUrl: "https://github.com/rambodc/uniq/pull/12", ship: { phase: "live", detail: "Live on uniqenergy.com." } })} />);
    expect(pendingCard).toContain("bd-done");
    expect(pendingCard).toContain("your change is ready");
    expect(failed).not.toContain("bd-done");
    expect(failed).not.toContain("your change is ready");
    expect(startFailureNote("Cursor could not complete that request. (Unknown model)", "error", null)).toContain("Send a message to start this build.");
    expect(startFailureNote("Cursor refused this request.", "error", "https://cursor.com/agents/bc-1")).toBe("Cursor refused this request.");
  });
  it("polls a running turn quickly and keeps checking after it is live", () => {
    const now = Date.parse("2026-11-22T18:10:00.000Z");
    expect(pollDelay("running", null, "2026-11-22T18:09:50.000Z", now)).toBe(1500);
    expect(pollDelay("running", null, "2026-11-22T18:00:00.000Z", now)).toBe(5000);
    expect(pollDelay("finished", "https://github.com/rambodc/uniq/pull/12", "2026-11-22T18:00:00.000Z", now, true, "live")).toBe(IDLE_POLL_MS);
    expect(pollDelay("finished", "https://github.com/rambodc/uniq/pull/12", "2026-11-22T18:00:00.000Z", now, true, "merged", "No changes.")).toBe(IDLE_POLL_MS);
    expect(IDLE_POLL_MS).toBeGreaterThanOrEqual(30_000);
    expect(IDLE_POLL_MS).toBeLessThanOrEqual(45_000);
    expect(pollEvery(IDLE_POLL_MS, true)).toBe(0);
    expect(pollEvery(IDLE_POLL_MS, false)).toBe(IDLE_POLL_MS);
    expect(pollDelay("finished", "https://github.com/rambodc/uniq/pull/12", "2026-11-22T18:00:00.000Z", now, true, "deploying")).toBe(8000);
    const app = readFileSync("src/builder/BuilderApp.tsx", "utf8");
    expect(app).toContain("visibilitychange");
    expect(app).toContain("getBuilderConversation(id, force)");
    expect(app).toContain("watchBuilderRun");
    expect(app).toContain("onSnapshot");
    const shown = html(<ChatColumn now={now} refreshing onRefresh={() => {}} conversation={conversation()} />);
    expect(shown).toContain('aria-label="Check for new messages"');
    expect(shown).toContain('title="Check for new messages"');
    expect(shown).toContain("bd-refresh spin");
    expect(shown.indexOf("Opened the pull request.")).toBeLessThan(shown.indexOf("Check for new messages"));
    expect(shown).not.toContain(">Check for new messages<");
    expect(workingStep([{ kind: "assistant", text: "Editing the Safety quiz." }])).toBe("Editing the Safety quiz.");
    expect(workLine([{ kind: "assistant", text: "Editing the Safety quiz." }], null).text).toBe("Editing the Safety quiz.");
    expect(workLine([{ kind: "user", text: "Hi" }], { step: "Reading files", text: "Looking at the page.", updatedAt: "t" })).toMatchObject({ text: "Looking at the page.", step: "Reading files", live: true });
    expect(preferLive({ step: "Thinking", text: "A", updatedAt: "2026-11-22T18:02:00.000Z" }, { step: "Editing files", text: "B", updatedAt: "2026-11-22T18:01:00.000Z" })?.step).toBe("Thinking");
    expect(elapsedLabel("2026-11-22T18:00:00.000Z", Date.parse("2026-11-22T18:01:05.000Z"))).toBe("1:05");
    expect(liveLinkLabel("https://uniqenergy.com/wells")).toBe("uniqenergy.com/wells");
  });
  it("keeps the composer at 16px and uses the theme tokens", () => {
    const css = readFileSync("src/builder/builder.css", "utf8");
    expect(css).toMatch(/\.bd-compose textarea\s*\{[^}]*font-size:\s*16px/);
    expect(css).toMatch(/--bg: var\(--portal-bg\)/);
    expect(css).toMatch(/var\(--bg\)/);
    expect(css).toMatch(/var\(--button\)/);
    expect(css).toMatch(/\.bd-refresh \{[^}]*color: var\(--accent\)/);
    expect(css).toMatch(/@keyframes bd-shimmer/);
    expect(css).toMatch(/@keyframes bd-arrive/);
    expect(css).toMatch(/@media \(prefers-reduced-motion: reduce\) \{[^}]*\.bd-work-step[^}]*animation: none/);
    expect(css).toMatch(/\.bd-done \{/);
    const portal = readFileSync("src/auth/portal.css", "utf8");
    expect(portal).toMatch(/\[data-theme="dark"\]/);
    expect(portal).toMatch(/\[data-theme="light"\]/);
    expect(readFileSync("src/auth/theme.ts", "utf8")).toMatch(/uniqenergy-portal-theme/);
    expect(readFileSync("src/auth/Theme.tsx", "utf8")).toMatch(/data-theme=\{theme\}/);
    const app = readFileSync("src/builder/BuilderApp.tsx", "utf8");
    const send = app.slice(app.indexOf("function send("), app.indexOf("async function notify"));
    expect(send.indexOf('setDraft("")')).toBeLessThan(send.indexOf("await"));
    expect(send).not.toContain("setBusy(true)");
    expect(send).toContain("heldFiles.current.get(retryId)");
    expect(send).not.toContain("retryId ? []");
    expect(app).not.toMatch(/textarea[^/]*disabled=\{busy\}/);
  });
  it("renders a question card, then only the chosen answer", () => {
    const asked = "QUESTION:\nWhich one should I build?\nA) Keep the current page\nB) A new Wells mini app";
    const base = conversation({ status: "finished", messages: [{ id: "u", kind: "user", text: "Hello", at: "2026-11-22T18:00:00.000Z" }, { id: "a", kind: "assistant", text: asked, at: "2026-11-22T18:00:04.000Z" }] });
    const open = html(<ChatColumn now={Date.parse("2026-11-22T18:00:05.000Z")} conversation={base} />);
    expect(open).toContain("Which one should I build?");
    const inline = html(<ChatColumn now={Date.parse("2026-11-22T18:00:05.000Z")} onOther={() => {}} conversation={conversation({ status: "finished", messages: [{ id: "u", kind: "user", text: "Hello", at: "2026-11-22T18:00:00.000Z" }, { id: "a", kind: "assistant", text: "QUESTION: Which view should this be? A) Executive dashboard B) Internal notes C) Something else", at: "2026-11-22T18:00:04.000Z" }] })} />);
    expect(inline).toContain("Executive dashboard");
    expect(inline).toContain("Something else");
    expect(inline).not.toContain("QUESTION:");
    expect(open).toContain("A new Wells mini app");
    expect(open).toContain("Other");
    expect(open).toContain("Submit");
    expect(open).not.toContain("QUESTION:");
    expect(pillOf("finished", null, true).label).toBe("Waiting for you");
    const answered = html(<ChatColumn now={Date.parse("2026-11-22T18:00:08.000Z")} conversation={base} extras={[{ id: "c", kind: "user", text: "B) A new Wells mini app", at: "2026-11-22T18:00:06.000Z", pending: "sending" }]} />);
    expect(answered).toContain("You chose B) A new Wells mini app.");
    expect(answered).toContain("Sending");
    const attached = ":::builder-files\nbuilder/uid/new/logo.png|logo.png|2048|image/png\n:::\nUse this logo on the card";
    const leaked = html(<ChatColumn now={Date.parse("2026-11-22T18:00:08.000Z")} conversation={conversation({ status: "finished", messages: [...base.messages, { id: "c", kind: "user", text: attached, at: "2026-11-22T18:00:06.000Z" }] })} />);
    expect(leaked).toContain("Answered below.");
    expect(leaked).toContain("Use this logo on the card");
    expect(leaked.split("Use this logo on the card").length - 1).toBe(1);
    expect(leaked).toContain("logo.png");
    expect(leaked).not.toContain(":::builder-files");
    expect(leaked).not.toContain("builder/uid/new/logo.png");
    expect(leaked).not.toContain("You chose Use this logo");
    const picked = ":::builder-files\nbuilder/uid/new/logo.png|logo.png|2048|image/png\n:::\nB) A new Wells mini app";
    const withFile = html(<ChatColumn now={Date.parse("2026-11-22T18:00:08.000Z")} conversation={conversation({ status: "finished", messages: [...base.messages, { id: "c", kind: "user", text: picked, at: "2026-11-22T18:00:06.000Z" }] })} />);
    expect(withFile).toContain("You chose B) A new Wells mini app.");
    expect(withFile).not.toContain("builder/uid/new/logo.png");
    expect(withFile).toContain("logo.png");
    expect(answered).not.toContain("Got it. Starting now.");
    expect(answered).not.toContain("Submit");
    const failed = html(<ChatColumn now={Date.parse("2026-11-22T18:00:08.000Z")} onRetry={() => {}} conversation={base} extras={[{ id: "c", kind: "user", text: "B) A new Wells mini app", at: "2026-11-22T18:00:06.000Z", pending: "failed", error: "Storage refused this file.", files: [{ name: "builder-lightbox-expand.jpg", size: 202 * 1024, contentType: "image/jpeg" }] }]} />);
    expect(failed).toContain("Not sent, Retry");
    expect(failed).toContain("Storage refused this file.");
    expect(failed).toContain("builder-lightbox-expand.jpg");
    const ack = html(<ChatColumn now={Date.parse("2026-11-22T18:00:08.000Z")} conversation={conversation({ messages: [{ id: "u", kind: "user", text: "Hello", at: "2026-11-22T18:00:00.000Z" }] })} extras={[{ id: "ack", kind: "assistant", text: "Got it. Starting now.", at: "2026-11-22T18:00:07.000Z", localAck: true }]} />);
    expect(ack).toContain("Got it. Starting now.");
    expect(openQuestion(base.messages)?.prompt).toBe("Which one should I build?");
    const current = conversation();
    const next = { ...current, status: "finished" as const, messages: current.messages.map((message) => ({ ...message })) };
    expect(mergeConversation(current, next).messages[0]).toBe(current.messages[0]);
    expect(sameThread(current, { ...current, live: { step: "Thinking", text: "Hello", updatedAt: "2026-11-22T18:01:00.000Z" } })).toBe(false);
    expect(dropSent([{ id: "p", kind: "user", text: "Add a notes mini app.", at: "2026-11-22T18:00:00.000Z", pending: "sending" }], current)).toEqual([]);
    expect(dropSent([{ id: "p", kind: "user", text: "Add a notes mini app.", at: "2026-11-22T19:00:00.000Z", pending: "sending" }], current)).toHaveLength(1);
  });
  it("walks mini app, ideas, preview, then build", () => {
    const now = Date.parse("2026-11-22T18:00:08.000Z");
    const asked = conversation({ status: "finished", messages: [{ id: "u", kind: "user", text: "Quiz leaderboard", at: "2026-11-22T18:00:00.000Z" }, { id: "a", kind: "assistant", text: "QUESTION:\nWhich mini app should this live in?\nA) Safety\nB) Party", at: "2026-11-22T18:00:02.000Z" }] });
    const mini = html(<ChatColumn now={now} conversation={asked} />);
    expect(mini).toContain("Which mini app should this live in?");
    expect(mini).toContain("Safety");
    const ideasText = "IDEAS:\nThree ways to show it.\n- Top 10 this month\n- Team totals\n- Personal best only\nBUILD:\nWhat: A top 10 for this month.\nParts: Safety and the portal navigation\nData: No schema change.\nCONTINUE:";
    const feat = conversation({ status: "finished", messages: [...asked.messages, { id: "c", kind: "user", text: "A) Safety", at: "2026-11-22T18:00:03.000Z" }, { id: "d", kind: "assistant", text: ideasText, at: "2026-11-22T18:00:04.000Z" }] });
    const ideasHtml = html(<ChatColumn now={now} onContinue={() => {}} conversation={feat} />);
    expect(ideasHtml).toContain("Top 10 this month");
    expect(ideasHtml).toContain("Here is what I");
    expect(ideasHtml).toContain("Parts");
    expect(ideasHtml).toContain("Safety and the portal navigation");
    expect(ideasHtml).toContain("Continue to preview");
    expect(ideasHtml).not.toContain("IDEAS:");
    expect(ideasHtml).not.toContain("CONTINUE:");
    const preview = conversation({ status: "finished", messages: [...feat.messages, { id: "e", kind: "user", text: "Continue to preview", at: "2026-11-22T18:00:05.000Z" }, { id: "f", kind: "assistant", text: "Here is the design.\nPREVIEW:\nSafety · Quiz leaderboard\nTop 10 this month. First names only.\nAPPROVE:", at: "2026-11-22T18:00:06.000Z" }] });
    const previewHtml = html(<ChatColumn now={now} onApprove={() => {}} onPreviewFix={() => {}} conversation={preview} />);
    expect(previewHtml).toContain("Here is the design.");
    expect(previewHtml).toContain("First names only.");
    expect(previewHtml).toContain(">Approve<");
    expect(previewHtml).toContain(">Fix<");
    expect(previewHtml).not.toContain("PREVIEW:");
    const second = conversation({ status: "finished", messages: [...preview.messages, { id: "q1", kind: "assistant", text: "QUESTION:\nShip it where?\nA) Safety\nB) Party", at: "2026-11-22T18:00:07.000Z" }, { id: "q2", kind: "assistant", text: "QUESTION:\nAnd also?\nA) Users\nB) Profile", at: "2026-11-22T18:00:07.500Z" }] });
    const stacked = html(<ChatColumn now={now} conversation={second} />);
    expect(stacked).toContain("Ship it where?");
    expect(stacked).not.toContain("And also?");
    expect(stacked).not.toContain("Start a new chat");
    expect(questionViews(second.messages).filter((item) => item.hidden)).toHaveLength(1);
    expect(readFileSync("src/builder/BuilderApp.tsx", "utf8")).toContain("Which mini app should this live in?");
    expect(readFileSync("src/builder/BuilderApp.tsx", "utf8")).toContain('send("Approved, build it")');
    expect(readFileSync("src/builder/BuilderApp.tsx", "utf8")).toContain("Tell me what to change");
  });
  it("sticks to the bottom only when the reader is already there, and names what arrived", () => {
    const box = { scrollHeight: 1000, scrollTop: 900, clientHeight: 100 };
    expect(isNearBottom(box)).toBe(true);
    expect(isNearBottom({ ...box, scrollTop: 800 })).toBe(false);
    const base = conversation();
    expect(sameThread(base, { ...base, messages: base.messages.map((message) => ({ ...message })) })).toBe(true);
    expect(sameThread(base, { ...base, status: "finished" })).toBe(false);
    expect(sameThread(base, { ...base, messages: [...base.messages, { id: "m3", kind: "assistant", text: "More.", at: "2026-11-22T18:05:00.000Z" }] })).toBe(false);
    expect(arrivalLabel([{ kind: "assistant", text: "Looking at the quiz scores." }])).toBe("New message");
    expect(arrivalLabel([{ kind: "assistant", text: "One." }, { kind: "assistant", text: "Two." }])).toBe("2 new messages");
    expect(arrivalLabel([{ kind: "assistant", text: "QUESTION:\nWhich one?\nA) Safety\nB) Party" }])).toBe("New question");
    expect(arrivalLabel([{ kind: "assistant", text: "PREVIEW:\nSafety board\nAPPROVE:" }])).toBe("Design ready");
    expect(readFileSync("src/builder/BuilderApp.tsx", "utf8")).not.toMatch(/node\.scrollTop = node\.scrollHeight; \}, \[/);
  });
});
